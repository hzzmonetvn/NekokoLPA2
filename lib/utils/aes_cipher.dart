import 'dart:typed_data';

/// Pure Dart implementation of FIPS 197 AES (128-bit and 256-bit) and CBC mode
/// with PKCS#7 padding. Replaces heavy third-party cryptographic dependencies
/// with zero-cost native Dart.
class AesCipher {
  final int _rounds;
  final List<Uint8List> _roundKeys;

  AesCipher._(this._rounds, this._roundKeys);

  factory AesCipher(Uint8List key) {
    final int nk;
    final int rounds;
    if (key.length == 16) {
      nk = 4;
      rounds = 10;
    } else if (key.length == 32) {
      nk = 8;
      rounds = 14;
    } else {
      throw ArgumentError('Invalid AES key length: ${key.length} (expected 16 or 32 bytes)');
    }

    final totalWords = (rounds + 1) * 4;
    final w = List<Uint8List>.generate(totalWords, (_) => Uint8List(4));

    for (var i = 0; i < nk; i++) {
      for (var j = 0; j < 4; j++) {
        w[i][j] = key[i * 4 + j];
      }
    }

    for (var i = nk; i < totalWords; i++) {
      var temp = Uint8List.fromList(w[i - 1]);
      if (i % nk == 0) {
        final rot = [
          _sBox[temp[1]] ^ _rcon[(i ~/ nk) - 1],
          _sBox[temp[2]],
          _sBox[temp[3]],
          _sBox[temp[0]],
        ];
        temp = Uint8List.fromList(rot);
      } else if (nk > 6 && (i % nk) == 4) {
        final sub = [
          _sBox[temp[0]],
          _sBox[temp[1]],
          _sBox[temp[2]],
          _sBox[temp[3]],
        ];
        temp = Uint8List.fromList(sub);
      }
      for (var j = 0; j < 4; j++) {
        w[i][j] = w[i - nk][j] ^ temp[j];
      }
    }

    final roundKeys = List<Uint8List>.generate(rounds + 1, (r) {
      final rk = Uint8List(16);
      for (var c = 0; c < 4; c++) {
        for (var j = 0; j < 4; j++) {
          rk[c * 4 + j] = w[r * 4 + c][j];
        }
      }
      return rk;
    });

    return AesCipher._(rounds, roundKeys);
  }

  void encryptBlock(Uint8List block) {
    _addRoundKey(block, 0);

    for (var r = 1; r < _rounds; r++) {
      _subBytes(block);
      _shiftRows(block);
      _mixColumns(block);
      _addRoundKey(block, r);
    }

    _subBytes(block);
    _shiftRows(block);
    _addRoundKey(block, _rounds);
  }

  void decryptBlock(Uint8List block) {
    _addRoundKey(block, _rounds);

    for (var r = _rounds - 1; r >= 1; r--) {
      _invShiftRows(block);
      _invSubBytes(block);
      _addRoundKey(block, r);
      _invMixColumns(block);
    }

    _invShiftRows(block);
    _invSubBytes(block);
    _addRoundKey(block, 0);
  }

  void _addRoundKey(Uint8List state, int round) {
    final rk = _roundKeys[round];
    for (var i = 0; i < 16; i++) {
      state[i] ^= rk[i];
    }
  }

  static void _subBytes(Uint8List state) {
    for (var i = 0; i < 16; i++) {
      state[i] = _sBox[state[i]];
    }
  }

  static void _invSubBytes(Uint8List state) {
    for (var i = 0; i < 16; i++) {
      state[i] = _invSBox[state[i]];
    }
  }

  static void _shiftRows(Uint8List s) {
    final t1 = s[1];
    s[1] = s[5];
    s[5] = s[9];
    s[9] = s[13];
    s[13] = t1;

    final t2 = s[2];
    final t6 = s[6];
    s[2] = s[10];
    s[6] = s[14];
    s[10] = t2;
    s[14] = t6;

    final t15 = s[15];
    s[15] = s[11];
    s[11] = s[7];
    s[7] = s[3];
    s[3] = t15;
  }

  static void _invShiftRows(Uint8List s) {
    final t13 = s[13];
    s[13] = s[9];
    s[9] = s[5];
    s[5] = s[1];
    s[1] = t13;

    final t2 = s[2];
    final t6 = s[6];
    s[2] = s[10];
    s[6] = s[14];
    s[10] = t2;
    s[14] = t6;

    final t3 = s[3];
    s[3] = s[7];
    s[7] = s[11];
    s[11] = s[15];
    s[15] = t3;
  }

  static int _xtime(int x) => ((x << 1) ^ (((x & 0x80) != 0) ? 0x1B : 0)) & 0xFF;

  static void _mixColumns(Uint8List s) {
    for (var c = 0; c < 4; c++) {
      final idx = c * 4;
      final s0 = s[idx];
      final s1 = s[idx + 1];
      final s2 = s[idx + 2];
      final s3 = s[idx + 3];

      s[idx] = _xtime(s0) ^ (_xtime(s1) ^ s1) ^ s2 ^ s3;
      s[idx + 1] = s0 ^ _xtime(s1) ^ (_xtime(s2) ^ s2) ^ s3;
      s[idx + 2] = s0 ^ s1 ^ _xtime(s2) ^ (_xtime(s3) ^ s3);
      s[idx + 3] = (_xtime(s0) ^ s0) ^ s1 ^ s2 ^ _xtime(s3);
    }
  }

  static int _gmul(int a, int b) {
    var p = 0;
    for (var i = 0; i < 8; i++) {
      if ((b & 1) != 0) p ^= a;
      a = _xtime(a);
      b >>= 1;
    }
    return p;
  }

  static void _invMixColumns(Uint8List s) {
    for (var c = 0; c < 4; c++) {
      final idx = c * 4;
      final s0 = s[idx];
      final s1 = s[idx + 1];
      final s2 = s[idx + 2];
      final s3 = s[idx + 3];

      s[idx] = _gmul(s0, 0x0E) ^ _gmul(s1, 0x0B) ^ _gmul(s2, 0x0D) ^ _gmul(s3, 0x09);
      s[idx + 1] = _gmul(s0, 0x09) ^ _gmul(s1, 0x0E) ^ _gmul(s2, 0x0B) ^ _gmul(s3, 0x0D);
      s[idx + 2] = _gmul(s0, 0x0D) ^ _gmul(s1, 0x09) ^ _gmul(s2, 0x0E) ^ _gmul(s3, 0x0B);
      s[idx + 3] = _gmul(s0, 0x0B) ^ _gmul(s1, 0x0D) ^ _gmul(s2, 0x09) ^ _gmul(s3, 0x0E);
    }
  }

  // ===========================================================================
  // CBC Mode & PKCS#7 Padding
  // ===========================================================================

  static Uint8List pkcs7Pad(Uint8List data) {
    final padLen = 16 - (data.length % 16);
    final out = Uint8List(data.length + padLen);
    out.setRange(0, data.length, data);
    for (var i = data.length; i < out.length; i++) {
      out[i] = padLen;
    }
    return out;
  }

  static Uint8List pkcs7Unpad(Uint8List data) {
    if (data.isEmpty || data.length % 16 != 0) {
      throw const FormatException('Invalid PKCS#7 data length');
    }
    final padLen = data[data.length - 1];
    if (padLen == 0 || padLen > 16 || padLen > data.length) {
      throw const FormatException('Invalid PKCS#7 pad length');
    }
    final splitPos = data.length - padLen;
    for (var i = splitPos; i < data.length; i++) {
      if (data[i] != padLen) {
        throw const FormatException('Invalid PKCS#7 padding byte');
      }
    }
    return Uint8List.sublistView(data, 0, splitPos);
  }

  static Uint8List cbcEncrypt(Uint8List key, Uint8List iv, Uint8List data) {
    if (iv.length != 16) throw ArgumentError('IV must be 16 bytes');
    if (data.length % 16 != 0) throw ArgumentError('Data length must be multiple of 16');

    final cipher = AesCipher(key);
    final out = Uint8List(data.length);
    final prev = Uint8List.fromList(iv);
    final block = Uint8List(16);

    for (var offset = 0; offset < data.length; offset += 16) {
      for (var i = 0; i < 16; i++) {
        block[i] = data[offset + i] ^ prev[i];
      }
      cipher.encryptBlock(block);
      out.setRange(offset, offset + 16, block);
      prev.setRange(0, 16, block);
    }

    return out;
  }

  static Uint8List cbcDecrypt(Uint8List key, Uint8List iv, Uint8List data) {
    if (iv.length != 16) throw ArgumentError('IV must be 16 bytes');
    if (data.length % 16 != 0) throw ArgumentError('Data length must be multiple of 16');

    final cipher = AesCipher(key);
    final out = Uint8List(data.length);
    final prev = Uint8List.fromList(iv);
    final block = Uint8List(16);

    for (var offset = 0; offset < data.length; offset += 16) {
      block.setRange(0, 16, data, offset);
      cipher.decryptBlock(block);
      for (var i = 0; i < 16; i++) {
        block[i] ^= prev[i];
      }
      out.setRange(offset, offset + 16, block);
      prev.setRange(0, 16, data, offset);
    }

    return out;
  }

